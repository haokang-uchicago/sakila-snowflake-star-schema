-- ADSP 31011 Week 4 — 03 Claude's own Snowflake identity: a SERVICE user with a key pair and a read-only role.
-- setup_agent.sh prints this file with your public key filled in. Run it once in Snowsight as ACCOUNTADMIN.
-- Assignment 4: the kit's grants, run on the SAKILA database (CLASSICMODELS replaced by SAKILA).
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS CLAUDE_RO COMMENT = 'read-only role for the Claude Code agent';
GRANT USAGE ON WAREHOUSE CLASS_WH TO ROLE CLAUDE_RO;
GRANT USAGE ON DATABASE SAKILA TO ROLE CLAUDE_RO;
GRANT USAGE ON ALL SCHEMAS IN DATABASE SAKILA TO ROLE CLAUDE_RO;
GRANT SELECT ON ALL TABLES IN DATABASE SAKILA TO ROLE CLAUDE_RO;
GRANT SELECT ON FUTURE TABLES IN DATABASE SAKILA TO ROLE CLAUDE_RO;
GRANT SELECT ON ALL VIEWS IN DATABASE SAKILA TO ROLE CLAUDE_RO;   -- the two STAGING views
GRANT SELECT ON FUTURE VIEWS IN DATABASE SAKILA TO ROLE CLAUDE_RO;   -- views created later (a replaced view is a new one)

CREATE USER IF NOT EXISTS CLAUDE_AGENT
  TYPE = SERVICE
  DEFAULT_ROLE = CLAUDE_RO
  DEFAULT_WAREHOUSE = CLASS_WH
  COMMENT = 'Claude Code agent — key-pair auth, read-only';
ALTER USER CLAUDE_AGENT SET RSA_PUBLIC_KEY = '<PUBLIC_KEY>';
GRANT ROLE CLAUDE_RO TO USER CLAUDE_AGENT;

-- Check: the role can read but cannot write
SHOW GRANTS TO ROLE CLAUDE_RO;
